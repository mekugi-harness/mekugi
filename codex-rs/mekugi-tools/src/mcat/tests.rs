use std::fs;

use pretty_assertions::assert_eq;
use tempfile::TempDir;

use super::execute;

fn s(args: &[&str]) -> Vec<String> {
    args.iter().map(|a| (*a).to_string()).collect()
}

#[test]
fn single_file_and_ranges() {
    let dir = TempDir::new().unwrap();
    let file = dir.path().join("sample.txt");
    fs::write(&file, "one\r\ntwo\rthree\nfour").unwrap();
    let path = file.to_string_lossy().into_owned();

    let out = execute(&s(&[&path]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stderr, "");
    assert_eq!(out.stdout, "one\r\ntwo\rthree\nfour");

    let out = execute(&s(&[&path, "2:3"]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stdout, "two\rthree\n");

    let out = execute(&s(&[&path, "2-4", "--number"]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stdout, "     2\ttwo\n     3\tthree\n     4\tfour\n");

    // 0:N normalizes start to 1.
    let out = execute(&s(&[&path, "0:2"]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stdout, "one\r\ntwo\r");
}

#[test]
fn head_and_tail_line_options() {
    let dir = TempDir::new().unwrap();
    let file = dir.path().join("lines.txt");
    fs::write(&file, "a\nb\nc\nd\ne\n").unwrap();
    let path = file.to_string_lossy().into_owned();

    let out = execute(&s(&["-n", "2", &path]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stdout, "a\nb\n");

    let out = execute(&s(&["-n", "2", "--tail", &path]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stdout, "d\ne\n");

    let out = execute(&s(&["--tail", &path]));
    assert_eq!(out.exit_code, 1);
    assert!(out.stderr.contains("--tail requires -n"));
}

#[test]
fn strict_range_validation_and_disambiguation() {
    let dir = TempDir::new().unwrap();
    let file = dir.path().join("a.txt");
    fs::write(&file, "one\ntwo\n").unwrap();
    let path = file.to_string_lossy().into_owned();

    // Bare line numbers, A:+C, A,B, reversed, zero, and non-canonical ranges are rejected strictly
    for bad_range in ["2", "10:+5", "1,3", "5:2", "0:0", "01:2"] {
        let out = execute(&s(&[&path, bad_range]));
        assert_eq!(out.exit_code, 1, "expected failure for {bad_range}");
        assert!(
            out.stderr.contains("invalid line range"),
            "unexpected stderr for {bad_range}: {:?}",
            out.stderr
        );
    }

    // -n rejects ranges
    let out = execute(&s(&["-n", "1-5", &path]));
    assert_eq!(out.exit_code, 1);
    assert!(out.stderr.contains("-n takes a row count, not a range"));

    // Range-like first operand requires ./
    let out = execute(&s(&["1:5"]));
    assert_eq!(out.exit_code, 1);
    assert!(out.stderr.contains("requires ./ prefix"));

    // PATH:ROW missing file rejected vs existing literal file
    let missing_colon = format!("{path}:2");
    let out = execute(&s(&[&missing_colon]));
    assert_eq!(out.exit_code, 1);
    assert!(
        out.stderr
            .contains("ranges must be separate START:END operands")
    );

    let literal_colon = dir.path().join("file:2");
    fs::write(&literal_colon, "literal\n").unwrap();
    let out = execute(&s(&[&literal_colon.to_string_lossy()]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stdout, "literal\n");

    // --max-tokens rejected as unknown option; allowed after --
    let out = execute(&s(&["--max-tokens", "100", &path]));
    assert_eq!(out.exit_code, 1);
    assert!(out.stderr.contains("unknown option"));

    let out = execute(&s(&["--", "--max-tokens=0"]));
    assert_eq!(out.exit_code, 1);
    assert!(out.stderr.contains("ENOENT"));
}

#[test]
fn utf8_eof_and_no_generated_advisory() {
    let dir = TempDir::new().unwrap();
    let bad = dir.path().join("bad.bin");
    fs::write(&bad, [0xff, 0xfe, b'\n']).unwrap();
    let out = execute(&s(&[&bad.to_string_lossy()]));
    assert_eq!(out.exit_code, 1);
    assert!(out.stderr.contains("not UTF-8"));

    let generated = dir.path().join("gen.go");
    fs::write(
        &generated,
        "// Code generated by protoc; DO NOT EDIT.\npackage gen\n",
    )
    .unwrap();
    // Plain single-file mcat preserves exact bytes without injecting advisory stderr.
    let out = execute(&s(&[&generated.to_string_lossy()]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(
        out.stdout,
        "// Code generated by protoc; DO NOT EDIT.\npackage gen\n"
    );
    assert_eq!(out.stderr, "");

    // Ranged read on a generated file does not inject generated-file advisories.
    let out = execute(&s(&[&generated.to_string_lossy(), "1:2"]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(
        out.stdout,
        "// Code generated by protoc; DO NOT EDIT.\npackage gen\n"
    );
    assert_eq!(out.stderr, "");

    let out = execute(&s(&[&generated.to_string_lossy(), "10:12"]));
    assert_eq!(out.exit_code, 1);
    assert!(out.stderr.contains("rows 10:12 past EOF (2 rows)"));
}

#[test]
fn bundle_framing_partial_failure_and_complete_large_file() {
    let dir = TempDir::new().unwrap();
    let a = dir.path().join("a.txt");
    let b = dir.path().join("b.txt");
    let missing = dir.path().join("missing.txt");
    fs::write(&a, "a1\na2\na3\n").unwrap();
    fs::write(&b, "b1\nb2\n").unwrap();

    let a_str = a.to_string_lossy().into_owned();
    let b_str = b.to_string_lossy().into_owned();
    let missing_str = missing.to_string_lossy().into_owned();

    // Multi-range same file + another file
    let out = execute(&s(&[&a_str, "1:1", "3:3", &b_str]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stderr, "");
    assert_eq!(
        out.stdout,
        format!(
            "--- 1 \"{a_str}\" 1:1 ---\na1\n\n--- 2 \"{a_str}\" 3:3 ---\na3\n\n--- 3 \"{b_str}\" 1:2 ---\nb1\nb2\n"
        )
    );

    // Partial failure preserves valid reads
    let out = execute(&s(&[&a_str, &missing_str]));
    assert_eq!(out.exit_code, 1);
    assert!(out.stdout.contains(&format!(
        "2 path=\"{missing_str}\" shown=none omitted=none status=failed"
    )));
    assert!(
        out.stdout
            .contains(&format!("--- 1 \"{a_str}\" 1:3 ---\na1\na2\na3\n"))
    );
    assert!(out.stderr.contains("ENOENT"));

    // Large file prints completely without truncation
    let large = dir.path().join("large.txt");
    let expected: String = (1..=3000)
        .map(|i| format!("line-{i:04} {}\n", "x".repeat(40)))
        .collect();
    fs::write(&large, &expected).unwrap();
    let out = execute(&s(&[&large.to_string_lossy()]));
    assert_eq!(out.exit_code, 0);
    assert_eq!(out.stderr, "");
    assert_eq!(out.stdout.len(), expected.len());
    assert_eq!(out.stdout, expected);
}
