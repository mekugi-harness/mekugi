const READ_BUNDLE_USAGE: &str =
    "mcat [-n N] [--tail] [--number] PATH [START:END ...] [PATH [START:END ...] ...]";
const MAX_READ_BUNDLE_READS: usize = 16;
const GENERATED_REMINDER: &str = "Generated file: edit the source and regenerate.";

#[derive(Clone, Debug, Default, Eq, PartialEq)]
struct McatOptions {
    lines: Option<u64>,
    tail: bool,
    number: bool,
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct ReadSelection {
    path: String,
    has_range: bool,
    start: u64,
    end: u64,
}

#[derive(Clone, Debug)]
struct ScanResult {
    stdout: String,
    stderr: String,
    failed: bool,
}

fn line_range_regex() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        #[allow(clippy::expect_used)]
        Regex::new(r"^[0-9]+[:-][0-9]+$").expect("valid line range regex")
    })
}

fn malformed_range_regex() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        #[allow(clippy::expect_used)]
        Regex::new(r"^([0-9]+)(:\+|,)([0-9]+)$").expect("valid malformed range regex")
    })
}

fn generated_marker_regex() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        #[allow(clippy::expect_used)]
        Regex::new(
            r"(?i)^(?:@generated\b|<auto-generated\b|code generated\b.*\bdo not edit\b|(?:this file (?:is|was) )?generated (?:by|from|with)\b|(?:this file (?:is|was) )?(?:(?:automatically generated|auto-generated|autogenerated)(?: file)?|generated file)(?:\s*$|[.:;!]|\s+(?:by|from|with)\b))",
        )
        .expect("valid generated marker regex")
    })
}

fn is_ascii_digits(s: &str) -> bool {
    !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit())
}

fn parse_canonical_u64(raw: &str) -> Option<u64> {
    if !is_ascii_digits(raw) {
        return None;
    }
    if raw.len() > 1 && raw.starts_with('0') {
        return None;
    }
    raw.parse::<u64>().ok()
}

fn parse_line_range(span: &str) -> Option<(u64, u64)> {
    let normalized = span.replace('-', ":");
    let (first, last) = normalized.split_once(':')?;
    let start = parse_canonical_u64(first)?;
    let end = parse_canonical_u64(last)?;
    if end < 1 || start > end || start > MAX_SAFE_INT || end > MAX_SAFE_INT {
        return None;
    }
    Some((start, end))
}

fn corrected_read_range(operand: &str) -> Option<String> {
    if is_ascii_digits(operand) {
        return Some(format!("{operand}:{operand}"));
    }
    let caps = malformed_range_regex().captures(operand)?;
    let first = caps.get(1)?.as_str();
    let sep = caps.get(2)?.as_str();
    let second = caps.get(3)?.as_str();
    if sep == "," {
        return Some(format!("{first}:{second}"));
    }
    let start = first.parse::<u64>().ok();
    let count = second.parse::<u64>().ok();
    match (start, count) {
        (Some(start), Some(count))
            if count > 0
                && start <= MAX_SAFE_INT
                && count <= (MAX_SAFE_INT + 1).saturating_sub(start.max(1)) =>
        {
            let s = start.max(1);
            Some(format!("{s}:{}", s + count - 1))
        }
        _ => Some(format!("{first}:END")),
    }
}

fn retry_command(args: &[&str]) -> String {
    let quoted: Vec<String> = args.iter().map(|arg| quote_shell_arg(arg)).collect();
    format!("mcat {}", quoted.join(" "))
}

fn parse_args(args: &[String]) -> Result<(Vec<ReadSelection>, McatOptions), String> {
    let mut options = McatOptions::default();
    let mut operands: Vec<&str> = Vec::new();
    let mut ended = false;
    let mut idx = 0;

    while idx < args.len() {
        let arg = args[idx].as_str();
        idx += 1;

        if !ended && arg == "--" {
            ended = true;
            continue;
        }
        if !ended && arg == "-n" {
            let raw = args.get(idx).map(String::as_str).unwrap_or("");
            if idx < args.len() {
                idx += 1;
            }
            if line_range_regex().is_match(raw) {
                let normalized = raw.replace('-', ":");
                return Err(format!(
                    "-n takes a row count, not a range; retry: mcat PATH {normalized}"
                ));
            }
            let parsed = parse_canonical_u64(raw).filter(|&n| (1..=MAX_SAFE_INT).contains(&n));
            if parsed.is_none() || options.lines.is_some() {
                return Err(format!(
                    "-n requires one integer from 1 to {MAX_SAFE_INT} and cannot repeat"
                ));
            }
            options.lines = parsed;
            continue;
        }
        if !ended && arg == "--tail" {
            if options.tail {
                return Err("--tail cannot repeat".to_string());
            }
            options.tail = true;
            continue;
        }
        if !ended && arg == "--number" {
            if options.number {
                return Err("--number cannot repeat".to_string());
            }
            options.number = true;
            continue;
        }
        if !ended && arg.starts_with('-') {
            return Err(format!("unknown option {arg:?}"));
        }
        operands.push(arg);
    }

    if options.tail && options.lines.is_none() {
        return Err("--tail requires -n".to_string());
    }

    let mut specs: Vec<ReadSelection> = Vec::new();
    for operand in operands {
        if line_range_regex().is_match(operand) {
            let Some(last) = specs.last_mut() else {
                let prefixed = format!("./{operand}");
                return Err(format!(
                    "range-like paths require ./; retry: {}",
                    retry_command(&[&prefixed])
                ));
            };
            let Some((start, end)) = parse_line_range(operand) else {
                return Err(
                    "line range must be START:END with canonical safe integers and START not after END"
                        .to_string(),
                );
            };
            let normalized_start = start.max(1);
            if !last.has_range {
                last.has_range = true;
                last.start = normalized_start;
                last.end = end;
            } else {
                let path = last.path.clone();
                specs.push(ReadSelection {
                    path,
                    has_range: true,
                    start: normalized_start,
                    end,
                });
            }
            continue;
        }

        if let Some(correction) = corrected_read_range(operand) {
            let path = specs.last().map_or("PATH", |spec| spec.path.as_str());
            return Err(format!(
                "invalid range {operand:?}; retry: {}",
                retry_command(&[path, &correction])
            ));
        }

        if let Some((path, row)) = operand.rsplit_once(':')
            && !path.is_empty()
            && is_ascii_digits(row)
        {
            match fs::metadata(operand) {
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                    let range = format!("{row}:{row}");
                    return Err(format!(
                        "ranges must be separate operands; retry: {}",
                        retry_command(&[path, &range])
                    ));
                }
                _ => {}
            }
        }

        if operand.is_empty() {
            return Err(format!("{READ_BUNDLE_USAGE} (1–16 reads)"));
        }

        specs.push(ReadSelection {
            path: operand.to_string(),
            has_range: false,
            start: 0,
            end: 0,
        });
    }

    if specs.is_empty() {
        return Err(READ_BUNDLE_USAGE.to_string());
    }
    if specs.len() > MAX_READ_BUNDLE_READS {
        let calls = specs.len().div_ceil(MAX_READ_BUNDLE_READS);
        return Err(format!(
            "received {} reads after argument expansion, exceeding the {MAX_READ_BUNDLE_READS}-read limit; split into {calls} mcat calls of at most {MAX_READ_BUNDLE_READS} reads each; repeat the path when splitting its ranges",
            specs.len()
        ));
    }
    if specs.len() > 1 && (options.lines.is_some() || options.tail) {
        return Err("-n and --tail require a single path".to_string());
    }

    Ok((specs, options))
}

#[derive(Default)]
struct GeneratedHeader {
    end_delim: Option<&'static str>,
    done: bool,
    found: bool,
}

impl GeneratedHeader {
    fn accept(&mut self, row: &str, first: bool) {
        if self.done {
            return;
        }
        let mut row = if first {
            row.strip_prefix('\u{feff}').unwrap_or(row)
        } else {
            row
        };
        row = row.trim();
        if first && row.starts_with("#!") {
            return;
        }
        while !row.is_empty() {
            if let Some(end_delim) = self.end_delim {
                if let Some((body, rest)) = row.split_once(end_delim) {
                    self.check(body.trim_start_matches('*').trim());
                    if self.done {
                        return;
                    }
                    self.end_delim = None;
                    row = rest.trim();
                    continue;
                } else {
                    self.check(row.trim_start_matches('*').trim());
                    return;
                }
            }
            let mut opened = false;
            for (start, end) in [("/*", "*/"), ("<!--", "-->"), ("(*", "*)")] {
                if let Some(rest) = row.strip_prefix(start) {
                    self.end_delim = Some(end);
                    row = rest.trim();
                    opened = true;
                    break;
                }
            }
            if opened {
                continue;
            }
            for prefix in ["//", "#", "--", ";", "%"] {
                if let Some(rest) = row.strip_prefix(prefix) {
                    self.check(rest.trim());
                    return;
                }
            }
            self.done = true;
            return;
        }
    }

    fn check(&mut self, comment: &str) {
        if generated_marker_regex().is_match(comment) {
            self.found = true;
            self.done = true;
        }
    }
}

fn generated_advisory(paths: &[String]) -> String {
    if paths.is_empty() {
        return String::new();
    }
    let quoted: Vec<String> = paths.iter().map(|p| quote_bundle_path(p)).collect();
    format!("mcat: {}: {GENERATED_REMINDER}\n", quoted.join(", "))
}

fn source_failure(path: &str, message: &str) -> ScanResult {
    ScanResult {
        stdout: String::new(),
        stderr: format!("mcat: {}: {message}\n", quote_json_string(path)),
        failed: true,
    }
}

fn source_failures(selections: &[ReadSelection], message: &str) -> Vec<ScanResult> {
    selections
        .iter()
        .map(|sel| source_failure(&sel.path, message))
        .collect()
}

struct SelectionAccumulator<'a> {
    selection: &'a ReadSelection,
    head_out: String,
    tail_rows: VecDeque<String>,
    selected_count: u64,
}

impl<'a> SelectionAccumulator<'a> {
    fn new(selection: &'a ReadSelection) -> Self {
        Self {
            selection,
            head_out: String::new(),
            tail_rows: VecDeque::new(),
            selected_count: 0,
        }
    }

    fn wants(&self, line: u64) -> bool {
        !self.selection.has_range || (line >= self.selection.start && line <= self.selection.end)
    }

    fn accept(&mut self, formatted_row: &str, options: &McatOptions) {
        self.selected_count += 1;
        if options.tail {
            if let Some(limit) = options.lines {
                if self.tail_rows.len() as u64 == limit {
                    self.tail_rows.pop_front();
                }
                self.tail_rows.push_back(formatted_row.to_string());
            } else {
                self.tail_rows.push_back(formatted_row.to_string());
            }
        } else if options
            .lines
            .is_none_or(|limit| self.selected_count <= limit)
        {
            self.head_out.push_str(formatted_row);
        }
    }

    fn finish(self, total_lines: u64, options: &McatOptions) -> ScanResult {
        if self.selection.has_range && self.selection.start > total_lines {
            return source_failure(
                &self.selection.path,
                &format!(
                    "rows {}:{} past EOF ({total_lines} rows)",
                    self.selection.start, self.selection.end
                ),
            );
        }
        let stdout = if options.tail {
            let mut out = String::new();
            for row in self.tail_rows {
                out.push_str(&row);
            }
            out
        } else {
            self.head_out
        };
        ScanResult {
            stdout,
            stderr: String::new(),
            failed: false,
        }
    }
}

/// Split UTF-8 text into logical rows separated by `\r\n`, `\r`, or `\n`.
/// Empty text yields 0 rows; a trailing unterminated segment yields a final row.
fn split_logical_lines(text: &str) -> Vec<&str> {
    let bytes = text.as_bytes();
    let mut rows = Vec::new();
    let mut start = 0usize;
    while start < bytes.len() {
        let mut end = start;
        while end < bytes.len() && bytes[end] != b'\r' && bytes[end] != b'\n' {
            end += 1;
        }
        rows.push(&text[start..end]);
        let mut next = end;
        if next < bytes.len() {
            next += 1;
            if bytes[end] == b'\r' && next < bytes.len() && bytes[next] == b'\n' {
                next += 1;
            }
        }
        start = next;
    }
    rows
}

fn scan_selections(selections: &[ReadSelection], options: &McatOptions) -> (Vec<ScanResult>, bool) {
    let path = &selections[0].path;
    let path_ref = Path::new(path);

    let meta = match fs::metadata(path_ref) {
        Ok(meta) => meta,
        Err(err) => return (source_failures(selections, &format_io_error(&err)), false),
    };
    if !meta.is_file() {
        return (source_failures(selections, "not a regular file"), false);
    }

    let mut file = match open_nonblocking(path_ref) {
        Ok(file) => file,
        Err(err) => return (source_failures(selections, &format_io_error(&err)), false),
    };
    let opened_meta = match file.metadata() {
        Ok(meta) => meta,
        Err(err) => return (source_failures(selections, &format_io_error(&err)), false),
    };
    if !opened_meta.is_file() {
        return (source_failures(selections, "not a regular file"), false);
    }

    let mut bytes = Vec::new();
    if let Err(err) = file.read_to_end(&mut bytes) {
        return (source_failures(selections, &format_io_error(&err)), false);
    }

    let Ok(text) = std::str::from_utf8(&bytes) else {
        return (source_failures(selections, "not UTF-8"), false);
    };

    let rows = split_logical_lines(text);
    let mut header = GeneratedHeader::default();
    let mut states: Vec<SelectionAccumulator<'_>> =
        selections.iter().map(SelectionAccumulator::new).collect();

    for (idx, row) in rows.iter().enumerate() {
        let line = (idx as u64) + 1;
        header.accept(row, line == 1);
        let any_wants = states.iter().any(|state| state.wants(line));
        if any_wants {
            let formatted = if options.number {
                format!("{line:6}\t{row}\n")
            } else {
                format!("{row}\n")
            };
            for state in &mut states {
                if state.wants(line) {
                    state.accept(&formatted, options);
                }
            }
        }
    }

    let total_lines = rows.len() as u64;
    let results: Vec<ScanResult> = states
        .into_iter()
        .map(|state| state.finish(total_lines, options))
        .collect();
    let generated = header.found && results.iter().any(|r| !r.failed);
    (results, generated)
}

fn bundle_row_count(text: &str) -> u64 {
    text.bytes().filter(|&b| b == b'\n').count() as u64
}

fn bundle_row_span(start: u64, text: &str) -> String {
    let count = bundle_row_count(text);
    if count == 0 {
        return "none".to_string();
    }
    format!("{start}:{}", start + count - 1)
}

fn prefix_bundle_diagnostic(path: &str, stderr: &str) -> String {
    if stderr.is_empty() {
        return String::new();
    }
    let prefix = format!("mcat: {}: ", quote_bundle_path(path));
    let mut out = String::new();
    for line in stderr.split_inclusive('\n') {
        if line.starts_with("mcat: \"") {
            out.push_str(line);
        } else {
            out.push_str(&prefix);
            out.push_str(line.strip_prefix("mcat: ").unwrap_or(line));
        }
    }
    if !stderr.ends_with('\n') {
        out.push('\n');
    }
    out
}

pub fn execute(args: &[String]) -> ToolOutput {
    let (specs, options) = match parse_args(args) {
        Ok(parsed) => parsed,
        Err(err) => {
            return ToolOutput {
                stdout: String::new(),
                stderr: format!("mcat: {err}\n"),
                exit_code: 1,
            };
        }
    };

    if specs.len() == 1 {
        let (mut results, generated) = scan_selections(&specs, &options);
        let mut res = results.remove(0);
        if generated {
            res.stderr
                .push_str(&generated_advisory(&[specs[0].path.clone()]));
        }
        return ToolOutput {
            stdout: res.stdout,
            stderr: res.stderr,
            exit_code: i32::from(res.failed),
        };
    }

    // Group reads by exact path so each file is scanned once.
    let mut by_path: HashMap<&str, Vec<usize>> = HashMap::new();
    for (idx, spec) in specs.iter().enumerate() {
        by_path.entry(spec.path.as_str()).or_default().push(idx);
    }

    let mut executions: Vec<Option<ScanResult>> = vec![None; specs.len()];
    let mut generated_paths: Vec<String> = Vec::new();
    for spec in &specs {
        let Some(indices) = by_path.remove(spec.path.as_str()) else {
            continue;
        };
        let group: Vec<ReadSelection> = indices.iter().map(|&i| specs[i].clone()).collect();
        let (outputs, generated) = scan_selections(&group, &options);
        if generated {
            generated_paths.push(spec.path.clone());
        }
        for (output, idx) in outputs.into_iter().zip(indices) {
            executions[idx] = Some(output);
        }
    }

    let mut manifest = String::new();
    let mut bodies = String::new();
    let mut diagnostics = String::new();
    let mut any_failed = false;

    for (idx, spec) in specs.iter().enumerate() {
        let exec = executions[idx].take().unwrap_or(ScanResult {
            stdout: String::new(),
            stderr: String::new(),
            failed: true,
        });
        let state = if exec.failed {
            any_failed = true;
            "failed"
        } else {
            "complete"
        };
        diagnostics.push_str(&prefix_bundle_diagnostic(&spec.path, &exec.stderr));

        let start = if spec.has_range { spec.start.max(1) } else { 1 };
        let path_quoted = quote_bundle_path(&spec.path);
        let span = bundle_row_span(start, &exec.stdout);
        if state != "complete" || exec.stdout.is_empty() {
            let _ = writeln!(
                manifest,
                "{} path={path_quoted} shown={span} omitted=none status={state}",
                idx + 1
            );
        }
        if !exec.stdout.is_empty() {
            let _ = write!(
                bodies,
                "\n--- {} {path_quoted} {span} ---\n{}",
                idx + 1,
                exec.stdout
            );
        }
    }

    let stdout = if manifest.is_empty() {
        bodies.strip_prefix('\n').unwrap_or(&bodies).to_string()
    } else {
        format!("{manifest}{bodies}")
    };
    diagnostics.push_str(&generated_advisory(&generated_paths));

    ToolOutput {
        stdout,
        stderr: diagnostics,
        exit_code: i32::from(any_failed),
    }
}

