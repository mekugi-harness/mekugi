const READ_BUNDLE_USAGE: &str =
    "mcat [-n N] [--tail] [--number] PATH [START:END ...] [PATH [START:END ...] ...]";
const MAX_READ_BUNDLE_READS: usize = 16;
const GENERATED_REMINDER: &str = "Generated file: edit the source and regenerate.";

fn generated_marker_regex() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        #[allow(clippy::expect_used)]
        Regex::new(
            r"(?i)^(?:@generated\b|<auto-generated\b|code generated\b.*\bdo not edit\b|(?:this file (?:is|was) )?generated (?:by|from|with)\b|(?:this file (?:is|was) )?(?:(?:automatically generated|auto-generated|autogenerated)(?: file)?|generated file)(?:\s*$|[.:;!]|\s+(?:by|from|with)\b))",
        )
        .expect("valid generated marker regex")
    })
}

#[derive(Default)]
struct GeneratedHeader {
    end_delim: Option<&'static str>,
    done: bool,
    found: bool,
}

impl GeneratedHeader {
    fn accept(&mut self, row: &str, first: bool) {
        if self.done {
            return;
        }
        let mut row = if first {
            row.strip_prefix('\u{feff}').unwrap_or(row)
        } else {
            row
        };
        row = row.trim();
        if first && row.starts_with("#!") {
            return;
        }
        while !row.is_empty() {
            if let Some(end_delim) = self.end_delim {
                if let Some((body, rest)) = row.split_once(end_delim) {
                    self.check(body.trim_start_matches('*').trim());
                    if self.done {
                        return;
                    }
                    self.end_delim = None;
                    row = rest.trim();
                    continue;
                } else {
                    self.check(row.trim_start_matches('*').trim());
                    return;
                }
            }
            let mut opened = false;
            for (start, end) in [("/*", "*/"), ("<!--", "-->"), ("(*", "*)")] {
                if let Some(rest) = row.strip_prefix(start) {
                    self.end_delim = Some(end);
                    row = rest.trim();
                    opened = true;
                    break;
                }
            }
            if opened {
                continue;
            }
            for prefix in ["//", "#", "--", ";", "%"] {
                if let Some(rest) = row.strip_prefix(prefix) {
                    self.check(rest.trim());
                    return;
                }
            }
            self.done = true;
            return;
        }
    }

    fn check(&mut self, comment: &str) {
        if generated_marker_regex().is_match(comment) {
            self.found = true;
            self.done = true;
        }
    }
}

fn generated_advisory(paths: &[String]) -> String {
    if paths.is_empty() {
        return String::new();
    }
    let quoted: Vec<String> = paths.iter().map(|p| quote_bundle_path(p)).collect();
    format!("mcat: {}: {GENERATED_REMINDER}\n", quoted.join(", "))
}

#[derive(Clone, Debug, Default, Eq, PartialEq)]
struct McatOptions {
    lines: Option<u64>,
    tail: bool,
    number: bool,
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct ReadSelection {
    path: String,
    has_range: bool,
    start: u64,
    end: u64,
}

#[derive(Clone, Debug)]
struct ScanResult {
    stdout: String,
    stderr: String,
    row_count: u64,
    failed: bool,
}

fn is_ascii_digits(s: &str) -> bool {
    !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit())
}

fn parse_canonical_u64(raw: &str) -> Option<u64> {
    if !is_ascii_digits(raw) || (raw.len() > 1 && raw.starts_with('0')) {
        return None;
    }
    raw.parse::<u64>().ok()
}

fn split_range_shape(s: &str) -> Option<(&str, &str)> {
    let (first, last) = s.split_once(':').or_else(|| s.split_once('-'))?;
    (is_ascii_digits(first) && is_ascii_digits(last)).then_some((first, last))
}

fn parse_line_range(span: &str) -> Option<(u64, u64)> {
    let (first, last) = split_range_shape(span)?;
    let start = parse_canonical_u64(first)?;
    let end = parse_canonical_u64(last)?;
    (end >= 1 && start <= end && end <= MAX_SAFE_INT).then_some((start, end))
}

fn is_malformed_range(s: &str) -> bool {
    if is_ascii_digits(s) {
        return true;
    }
    s.split_once(":+")
        .or_else(|| s.split_once(','))
        .is_some_and(|(a, b)| is_ascii_digits(a) && is_ascii_digits(b))
}

fn parse_args(args: &[String]) -> Result<(Vec<ReadSelection>, McatOptions), String> {
    let mut options = McatOptions::default();
    let mut operands: Vec<&str> = Vec::new();
    let mut ended = false;
    let mut idx = 0;

    while idx < args.len() {
        let arg = args[idx].as_str();
        idx += 1;

        if !ended && arg == "--" {
            ended = true;
            continue;
        }
        if !ended && arg == "-n" {
            let raw = args.get(idx).map(String::as_str).unwrap_or("");
            if idx < args.len() {
                idx += 1;
            }
            if split_range_shape(raw).is_some() {
                return Err("-n takes a row count, not a range".to_string());
            }
            let parsed = parse_canonical_u64(raw).filter(|&n| (1..=MAX_SAFE_INT).contains(&n));
            if parsed.is_none() || options.lines.is_some() {
                return Err(format!(
                    "-n requires one integer from 1 to {MAX_SAFE_INT} and cannot repeat"
                ));
            }
            options.lines = parsed;
            continue;
        }
        if !ended && arg == "--tail" {
            if options.tail {
                return Err("--tail cannot repeat".to_string());
            }
            options.tail = true;
            continue;
        }
        if !ended && arg == "--number" {
            if options.number {
                return Err("--number cannot repeat".to_string());
            }
            options.number = true;
            continue;
        }
        if !ended && arg.starts_with('-') {
            return Err(format!("unknown option {arg:?}"));
        }
        operands.push(arg);
    }

    if options.tail && options.lines.is_none() {
        return Err("--tail requires -n".to_string());
    }

    let mut specs: Vec<ReadSelection> = Vec::new();
    for operand in operands {
        if split_range_shape(operand).is_some() {
            let Some(last) = specs.last_mut() else {
                return Err(format!("range-like path {operand:?} requires ./ prefix"));
            };
            let Some((start, end)) = parse_line_range(operand) else {
                return Err(format!(
                    "invalid line range {operand:?}: expected START:END with canonical integers and START <= END"
                ));
            };
            let normalized_start = start.max(1);
            if !last.has_range {
                last.has_range = true;
                last.start = normalized_start;
                last.end = end;
            } else {
                let path = last.path.clone();
                specs.push(ReadSelection {
                    path,
                    has_range: true,
                    start: normalized_start,
                    end,
                });
            }
            continue;
        }

        if is_malformed_range(operand) {
            return Err(format!(
                "invalid line range {operand:?}: expected START:END"
            ));
        }

        if let Some((path, row)) = operand.rsplit_once(':')
            && !path.is_empty()
            && is_ascii_digits(row)
            && matches!(fs::metadata(operand), Err(err) if err.kind() == std::io::ErrorKind::NotFound)
        {
            return Err("ranges must be separate START:END operands".to_string());
        }

        if operand.is_empty() {
            return Err(format!("{READ_BUNDLE_USAGE} (1–16 reads)"));
        }

        specs.push(ReadSelection {
            path: operand.to_string(),
            has_range: false,
            start: 0,
            end: 0,
        });
    }

    if specs.is_empty() {
        return Err(READ_BUNDLE_USAGE.to_string());
    }
    if specs.len() > MAX_READ_BUNDLE_READS {
        let calls = specs.len().div_ceil(MAX_READ_BUNDLE_READS);
        return Err(format!(
            "received {} reads after argument expansion, exceeding the {MAX_READ_BUNDLE_READS}-read limit; split into {calls} mcat calls of at most {MAX_READ_BUNDLE_READS} reads each; repeat the path when splitting its ranges",
            specs.len()
        ));
    }
    if specs.len() > 1 && (options.lines.is_some() || options.tail) {
        return Err("-n and --tail require a single path".to_string());
    }

    Ok((specs, options))
}

fn source_failure(path: &str, message: &str) -> ScanResult {
    ScanResult {
        stdout: String::new(),
        stderr: format!("mcat: {}: {message}\n", quote_json_string(path)),
        row_count: 0,
        failed: true,
    }
}

fn source_failures(selections: &[ReadSelection], message: &str) -> Vec<ScanResult> {
    selections
        .iter()
        .map(|sel| source_failure(&sel.path, message))
        .collect()
}

struct SelectionAccumulator<'a> {
    selection: &'a ReadSelection,
    head_out: String,
    head_rows: u64,
    tail_rows: VecDeque<String>,
    selected_count: u64,
}

impl<'a> SelectionAccumulator<'a> {
    fn new(selection: &'a ReadSelection) -> Self {
        Self {
            selection,
            head_out: String::new(),
            head_rows: 0,
            tail_rows: VecDeque::new(),
            selected_count: 0,
        }
    }

    fn wants(&self, line: u64) -> bool {
        !self.selection.has_range || (line >= self.selection.start && line <= self.selection.end)
    }

    fn accept(&mut self, formatted_row: &str, options: &McatOptions) {
        self.selected_count += 1;
        if options.tail {
            if options
                .lines
                .is_some_and(|limit| self.tail_rows.len() as u64 == limit)
            {
                self.tail_rows.pop_front();
            }
            self.tail_rows.push_back(formatted_row.to_string());
        } else if options
            .lines
            .is_none_or(|limit| self.selected_count <= limit)
        {
            self.head_out.push_str(formatted_row);
            self.head_rows += 1;
        }
    }

    fn finish(self, total_lines: u64, options: &McatOptions) -> ScanResult {
        if self.selection.has_range && self.selection.start > total_lines {
            return source_failure(
                &self.selection.path,
                &format!(
                    "rows {}:{} past EOF ({total_lines} rows)",
                    self.selection.start, self.selection.end
                ),
            );
        }
        let (stdout, row_count) = if options.tail {
            let count = self.tail_rows.len() as u64;
            let out: String = self.tail_rows.into_iter().collect();
            (out, count)
        } else {
            (self.head_out, self.head_rows)
        };
        ScanResult {
            stdout,
            stderr: String::new(),
            row_count,
            failed: false,
        }
    }
}

fn open_verified_regular_file(path: &str) -> Result<fs::File, String> {
    let path_ref = Path::new(path);
    let meta = fs::metadata(path_ref).map_err(|err| format_io_error(&err))?;
    if !meta.is_file() {
        return Err("not a regular file".to_string());
    }
    let file = open_nonblocking(path_ref).map_err(|err| format_io_error(&err))?;
    let opened_meta = file.metadata().map_err(|err| format_io_error(&err))?;
    if !opened_meta.is_file() {
        return Err("not a regular file".to_string());
    }
    Ok(file)
}

/// Read one logical line (delimited by `\r\n`, `\r`, or `\n`) while preserving the
/// exact original line-ending bytes. Returns `Ok(None)` at EOF.
fn read_logical_line_raw<R: BufRead>(
    reader: &mut R,
    buf: &mut Vec<u8>,
) -> std::io::Result<Option<usize>> {
    buf.clear();
    loop {
        let available = reader.fill_buf()?;
        if available.is_empty() {
            return Ok((!buf.is_empty()).then_some(buf.len()));
        }
        if let Some(pos) = available.iter().position(|&b| b == b'\n' || b == b'\r') {
            let delim = available[pos];
            buf.extend_from_slice(&available[..=pos]);
            let content_len = buf.len() - 1;
            reader.consume(pos + 1);
            if delim == b'\r' && reader.fill_buf()?.first() == Some(&b'\n') {
                buf.push(b'\n');
                reader.consume(1);
            }
            return Ok(Some(content_len));
        }
        buf.extend_from_slice(available);
        let consumed = available.len();
        reader.consume(consumed);
    }
}

fn stream_utf8_pass(file: &mut fs::File, mut sink: Option<&mut dyn Write>) -> Result<(), String> {
    const CHUNK_SIZE: usize = 64 * 1024;
    let mut carry = [0u8; 4];
    let mut carry_len = 0usize;
    let mut chunk = vec![0u8; CHUNK_SIZE];
    let mut work = Vec::with_capacity(CHUNK_SIZE + 4);

    loop {
        let read = file.read(&mut chunk).map_err(|err| format_io_error(&err))?;
        if read == 0 {
            break;
        }
        work.clear();
        work.extend_from_slice(&carry[..carry_len]);
        work.extend_from_slice(&chunk[..read]);
        carry_len = 0;

        let emit_len = match std::str::from_utf8(&work) {
            Ok(_) => work.len(),
            Err(err) => {
                if err.error_len().is_some() {
                    return Err("not UTF-8".to_string());
                }
                let valid_up_to = err.valid_up_to();
                let rem = &work[valid_up_to..];
                carry[..rem.len()].copy_from_slice(rem);
                carry_len = rem.len();
                valid_up_to
            }
        };
        if emit_len > 0
            && let Some(out) = sink.as_deref_mut()
        {
            out.write_all(&work[..emit_len])
                .map_err(|err| format_io_error(&err))?;
        }
    }

    if carry_len > 0 {
        return Err("not UTF-8".to_string());
    }
    Ok(())
}

/// Stream a single plain file directly to `stdout` without buffering the whole file
/// into memory or altering `\r\n`, `\r`, `\n`, or missing trailing newlines.
fn stream_plain_file(path: &str, stdout: &mut impl Write, stderr: &mut impl Write) -> i32 {
    let mut run = || -> Result<(), String> {
        let mut file = open_verified_regular_file(path)?;
        // Pass 1: streaming UTF-8 validation in O(1) memory.
        stream_utf8_pass(&mut file, None)?;
        // Pass 2: stream raw bytes while re-validating UTF-8 against concurrent appends.
        file.seek(SeekFrom::Start(0))
            .map_err(|err| format_io_error(&err))?;
        stream_utf8_pass(&mut file, Some(stdout))
    };
    if let Err(message) = run() {
        let _ = writeln!(stderr, "mcat: {}: {message}", quote_json_string(path));
        return 1;
    }
    0
}

fn compute_stop_after_line(selections: &[ReadSelection], options: &McatOptions) -> Option<u64> {
    if options.tail {
        return None;
    }
    if let [sel] = selections {
        return match (sel.has_range, options.lines) {
            (true, Some(limit)) => Some(
                sel.start
                    .saturating_add(limit)
                    .saturating_sub(1)
                    .min(sel.end),
            ),
            (true, None) => Some(sel.end),
            (false, Some(limit)) => Some(limit),
            (false, None) => None,
        };
    }
    selections
        .iter()
        .all(|sel| sel.has_range)
        .then(|| selections.iter().map(|sel| sel.end).max())
        .flatten()
}

fn scan_selections(selections: &[ReadSelection], options: &McatOptions) -> (Vec<ScanResult>, bool) {
    let path = &selections[0].path;
    let file = match open_verified_regular_file(path) {
        Ok(file) => file,
        Err(message) => return (source_failures(selections, &message), false),
    };

    let stop_after_line = compute_stop_after_line(selections, options);
    let mut reader = BufReader::with_capacity(64 * 1024, file);
    let mut raw_buf = Vec::new();
    let mut header = GeneratedHeader::default();
    let mut states: Vec<SelectionAccumulator<'_>> =
        selections.iter().map(SelectionAccumulator::new).collect();
    let mut total_lines = 0u64;

    loop {
        let content_len = match read_logical_line_raw(&mut reader, &mut raw_buf) {
            Ok(Some(content_len)) => content_len,
            Ok(None) => break,
            Err(err) => return (source_failures(selections, &format_io_error(&err)), false),
        };
        let Ok(raw_line) = std::str::from_utf8(&raw_buf) else {
            return (source_failures(selections, "not UTF-8"), false);
        };
        total_lines += 1;
        let line = total_lines;
        if !header.done {
            header.accept(&raw_line[..content_len], line == 1);
        }
        if states.iter().any(|state| state.wants(line)) {
            let formatted = if options.number {
                format!("{line:6}\t{}\n", &raw_line[..content_len])
            } else {
                raw_line.to_string()
            };
            for state in &mut states {
                if state.wants(line) {
                    state.accept(&formatted, options);
                }
            }
        }
        if stop_after_line.is_some_and(|max_line| line >= max_line) {
            break;
        }
    }

    let results: Vec<ScanResult> = states
        .into_iter()
        .map(|state| state.finish(total_lines, options))
        .collect();
    let generated = header.found && results.iter().any(|r| !r.failed);
    (results, generated)
}

fn bundle_row_span(start: u64, count: u64) -> String {
    if count == 0 {
        return "none".to_string();
    }
    format!("{start}:{}", start + count - 1)
}

fn prefix_bundle_diagnostic(path: &str, stderr: &str) -> String {
    if stderr.is_empty() {
        return String::new();
    }
    let prefix = format!("mcat: {}: ", quote_bundle_path(path));
    let mut out = String::new();
    for line in stderr.split_inclusive('\n') {
        if line.starts_with("mcat: \"") {
            out.push_str(line);
        } else {
            out.push_str(&prefix);
            out.push_str(line.strip_prefix("mcat: ").unwrap_or(line));
        }
    }
    if !stderr.ends_with('\n') {
        out.push('\n');
    }
    out
}

pub fn execute_to_writers(
    args: &[String],
    stdout_writer: &mut impl Write,
    stderr_writer: &mut impl Write,
) -> i32 {
    let (specs, options) = match parse_args(args) {
        Ok(parsed) => parsed,
        Err(err) => {
            let _ = writeln!(stderr_writer, "mcat: {err}");
            return 1;
        }
    };

    if specs.len() == 1
        && !specs[0].has_range
        && !options.number
        && options.lines.is_none()
        && !options.tail
    {
        return stream_plain_file(&specs[0].path, stdout_writer, stderr_writer);
    }

    if specs.len() == 1 {
        let (mut results, generated) = scan_selections(&specs, &options);
        let res = results.remove(0);
        let mut exit_code = i32::from(res.failed);
        if let Err(err) = stdout_writer.write_all(res.stdout.as_bytes()) {
            let _ = writeln!(
                stderr_writer,
                "mcat: {}: {}",
                quote_json_string(&specs[0].path),
                format_io_error(&err)
            );
            exit_code = 1;
        }
        let _ = stderr_writer.write_all(res.stderr.as_bytes());
        if generated {
            let _ =
                stderr_writer.write_all(generated_advisory(&[specs[0].path.clone()]).as_bytes());
        }
        return exit_code;
    }

    // Group reads by exact path so each file is scanned once.
    let mut by_path: HashMap<&str, Vec<usize>> = HashMap::new();
    for (idx, spec) in specs.iter().enumerate() {
        by_path.entry(spec.path.as_str()).or_default().push(idx);
    }

    let mut executions: Vec<Option<ScanResult>> = vec![None; specs.len()];
    let mut generated_paths = Vec::new();
    for spec in &specs {
        let Some(indices) = by_path.remove(spec.path.as_str()) else {
            continue;
        };
        let group: Vec<ReadSelection> = indices.iter().map(|&i| specs[i].clone()).collect();
        let (outputs, generated) = scan_selections(&group, &options);
        if generated {
            generated_paths.push(spec.path.clone());
        }
        for (output, idx) in outputs.into_iter().zip(indices) {
            executions[idx] = Some(output);
        }
    }

    let mut manifest = String::new();
    let mut bodies = String::new();
    let mut diagnostics = String::new();
    let mut any_failed = false;

    for (idx, spec) in specs.iter().enumerate() {
        let exec = executions[idx].take().unwrap_or(ScanResult {
            stdout: String::new(),
            stderr: String::new(),
            row_count: 0,
            failed: true,
        });
        let state = if exec.failed {
            any_failed = true;
            "failed"
        } else {
            "complete"
        };
        diagnostics.push_str(&prefix_bundle_diagnostic(&spec.path, &exec.stderr));

        let start = if spec.has_range { spec.start.max(1) } else { 1 };
        let path_quoted = quote_bundle_path(&spec.path);
        let span = bundle_row_span(start, exec.row_count);
        if state != "complete" || exec.stdout.is_empty() {
            let _ = writeln!(
                manifest,
                "{} path={path_quoted} shown={span} omitted=none status={state}",
                idx + 1
            );
        }
        if !exec.stdout.is_empty() {
            let _ = write!(
                bodies,
                "\n--- {} {path_quoted} {span} ---\n{}",
                idx + 1,
                exec.stdout
            );
            if !exec.stdout.ends_with('\n') {
                bodies.push('\n');
            }
        }
    }

    let stdout = if manifest.is_empty() {
        bodies.strip_prefix('\n').unwrap_or(&bodies).to_string()
    } else {
        format!("{manifest}{bodies}")
    };
    diagnostics.push_str(&generated_advisory(&generated_paths));

    let mut exit_code = i32::from(any_failed);
    if let Err(err) = stdout_writer.write_all(stdout.as_bytes()) {
        let _ = writeln!(
            stderr_writer,
            "mcat: write stdout: {}",
            format_io_error(&err)
        );
        exit_code = 1;
    }
    let _ = stderr_writer.write_all(diagnostics.as_bytes());
    exit_code
}

#[cfg(test)]
pub fn execute(args: &[String]) -> ToolOutput {
    let mut stdout = Vec::new();
    let mut stderr = Vec::new();
    let exit_code = execute_to_writers(args, &mut stdout, &mut stderr);
    ToolOutput {
        stdout: String::from_utf8(stdout).unwrap_or_default(),
        stderr: String::from_utf8(stderr).unwrap_or_default(),
        exit_code,
    }
}

